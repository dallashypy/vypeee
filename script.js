    var purpleRain = ['rgba(139, 92, 246, 0.2)', 'rgba(167, 139, 250, 0.3)', 'rgba(196, 181, 253, 0.15)'];

    function resizeCanvas() {
      var dpr = Math.min(window.devicePixelRatio || 1, 2);
      width = window.innerWidth;
      height = window.innerHeight;
      canvas.width = Math.floor(width * dpr);
      canvas.height = Math.floor(height * dpr);
      canvas.style.width = width + 'px';
      canvas.style.height = height + 'px';
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      createRain();
    }

    function createRain() {
      drops = [];
      var amount = reducedMotion ? 0 : Math.min(50, Math.max(20, Math.floor(width / 30)));
      for (var i = 0; i < amount; i++) {
        var length = 10 + Math.random() * 20;
        drops.push({
          x: Math.random() * width,
          y: Math.random() * height,
          length: length,
          speed: 0.8 + Math.random() * 1.5,
          drift: 0.1 + Math.random() * 0.2,
          alpha: 0.1 + Math.random() * 0.2,
          color: purpleRain[Math.floor(Math.random() * purpleRain.length)]
        });
      }
    }

    function drawRain() {
      ctx.clearRect(0, 0, width, height);
      ctx.lineCap = 'round';
      for (var i = 0; i < drops.length; i++) {
        var drop = drops[i];
        var gradient = ctx.createLinearGradient(drop.x, drop.y, drop.x + drop.drift * 4, drop.y + drop.length);
        gradient.addColorStop(0, 'rgba(139, 92, 246, 0)');
        gradient.addColorStop(1, drop.color);
        ctx.beginPath();
        ctx.moveTo(drop.x, drop.y);
        ctx.lineTo(drop.x + drop.drift * 4, drop.y + drop.length);
        ctx.strokeStyle = gradient;
        ctx.globalAlpha = drop.alpha;
        ctx.lineWidth = 1;
        ctx.stroke();
        if (!reducedMotion) {
          drop.y += drop.speed;
          drop.x += drop.drift;
          if (drop.y > height + drop.length) {
            drop.y = -drop.length - Math.random() * 100;
            drop.x = Math.random() * width;
          }
          if (drop.x > width + 5) drop.x = -5;
        }
      }
      ctx.globalAlpha = 1;
    }

    function animateRain() {
      drawRain();
      if (!reducedMotion) requestAnimationFrame(animateRain);
    }

    resizeCanvas();
    animateRain();
    window.addEventListener('resize', resizeCanvas, { passive: true });
