function applyLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  try { localStorage.setItem('vype-lang', lang); } catch (e) {}
  document.documentElement.lang = lang === 'pt' ? 'pt-br' : lang;

  var dict = translations[lang];
  var i18nEls = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < i18nEls.length; i++) {
    var el = i18nEls[i];
    var key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  }

  var currentLangEl = document.getElementById('current-lang');
  if (currentLangEl) currentLangEl.textContent = langLabels[lang];

  var langItems = document.querySelectorAll('.lang-item');
  for (var j = 0; j < langItems.length; j++) {
    if (langItems[j].getAttribute('data-lang') === lang) {
      langItems[j].classList.add('active');
    } else {
      langItems[j].classList.remove('active');
    }
  }

  startTypewriter();
}

function updateActiveNav() {
  var links = document.querySelectorAll('.nav-link');
  var sections = document.querySelectorAll('main section[id]');
  if (!sections.length) return;

  var viewportH = window.innerHeight;
  var scrollY = window.pageYOffset || document.documentElement.scrollTop || 0;
  var docH = document.documentElement.scrollHeight;
  var currentId = sections[0].id;
  var referenceLine = Math.min(viewportH * 0.38, 260);

  if (scrollY + viewportH >= docH - 8) {
    currentId = sections[sections.length - 1].id;
  } else {
    for (var i = 0; i < sections.length; i++) {
      if (sections[i].getBoundingClientRect().top <= referenceLine) {
        currentId = sections[i].id;
      } else {
        break;
      }
    }
  }

  for (var k = 0; k < links.length; k++) {
    var active = links[k].getAttribute('href') === '#' + currentId;
    links[k].classList.toggle('active', active);
    if (active) links[k].setAttribute('aria-current', 'location');
    else links[k].removeAttribute('aria-current');
  }
}

var typewriterTimeout;
function startTypewriter() {
  var el = document.getElementById('typewriter');
  if (!el) return;
  
  clearTimeout(typewriterTimeout);
  
  var text = "Just a Programmer";
  el.textContent = '';
  var i = 0;
  
  function type() {
    if (i < text.length) {
      el.textContent += text.charAt(i);
      i++;
      typewriterTimeout = setTimeout(type, 80);
    }
  }
  type();
}

function initMusic() {
  var audio = document.getElementById('bg-music');
  var btn = document.getElementById('music-toggle');
  var volumePanel = document.getElementById('volume-panel');
  var volumeSlider = document.getElementById('volume-slider');

  if (!audio) return;

  var BASE_VOLUME = 0.35;
  audio.volume = BASE_VOLUME;
  audio.loop = true;
  audio.preload = 'auto';

  var savedVolume = null;
  try { savedVolume = parseFloat(localStorage.getItem('vype-volume')); } catch (e) {}
  if (!isNaN(savedVolume) && savedVolume >= 0 && savedVolume <= 1) {
    audio.volume = savedVolume;
  }

  var audioCtx = null;
  var sourceNode = null;
  var filterNode = null;
  var gainNode = null;
  var webAudioReady = false;
  var isPlaying = false;

  function setupWebAudio() {
    if (webAudioReady) return true;
    var AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return false;
    try {
      audioCtx = new AudioCtx();
      sourceNode = audioCtx.createMediaElementSource(audio);
      filterNode = audioCtx.createBiquadFilter();
      filterNode.type = 'lowpass';
      filterNode.frequency.value = 900;
      filterNode.Q.value = 0.7;
      gainNode = audioCtx.createGain();
      gainNode.gain.value = 1.0;
      sourceNode.connect(filterNode);
      filterNode.connect(gainNode);
      gainNode.connect(audioCtx.destination);
      webAudioReady = true;
      return true;
    } catch (e) {
      webAudioReady = false;
      return false;
    }
  }

  function setPlayingUI(playing) {
    isPlaying = playing;
    if (!btn) return;
    btn.classList.toggle('playing', playing);
    btn.setAttribute('aria-pressed', String(playing));
    var icon = btn.querySelector('i');
    if (icon) {
      icon.classList.toggle('fa-volume-high', playing);
      icon.classList.toggle('fa-volume-xmark', !playing);
    }
    updateSliderFill();
  }

  function updateSliderFill() {
    if (!volumeSlider) return;
    var val = parseFloat(volumeSlider.value) || 0;
    var pct = val * 100;
    volumeSlider.style.background =
      'linear-gradient(to right, #a78bfa 0%, #a78bfa ' + pct + '%, rgba(255,255,255,0.12) ' + pct + '%, rgba(255,255,255,0.12) 100%)';
  }

  function playMusic() {
    setupWebAudio();
    if (audioCtx && audioCtx.state === 'suspended') {
      audioCtx.resume().catch(function () {});
    }
    var p = audio.play();
    if (p && typeof p.then === 'function') {
      p.then(function () { setPlayingUI(true); }).catch(function () { setPlayingUI(false); });
    } else {
      setPlayingUI(true);
    }
  }

  function pauseMusic() {
    audio.pause();
    setPlayingUI(false);
  }

  playMusic();

  function tryStartOnInteraction() {
    if (isPlaying) {
      removeInteractionListeners();
      return;
    }
    playMusic();
    if (isPlaying) removeInteractionListeners();
  }

  function removeInteractionListeners() {
    window.removeEventListener('click', tryStartOnInteraction, true);
    window.removeEventListener('touchstart', tryStartOnInteraction, true);
    window.removeEventListener('keydown', tryStartOnInteraction, true);
    window.removeEventListener('pointerdown', tryStartOnInteraction, true);
  }

  window.addEventListener('click', tryStartOnInteraction, true);
  window.addEventListener('touchstart', tryStartOnInteraction, true);
  window.addEventListener('keydown', tryStartOnInteraction, true);
  window.addEventListener('pointerdown', tryStartOnInteraction, true);

  if (btn && volumePanel) {
    btn.addEventListener('click', function (e) {
      e.stopPropagation();
      e.preventDefault();
      volumePanel.classList.toggle('visible');
    });
    btn.addEventListener('dblclick', function (e) {
      e.preventDefault();
      e.stopPropagation();
      if (audio.paused) playMusic();
      else pauseMusic();
    });
    document.addEventListener('click', function (e) {
      if (!volumePanel.contains(e.target) && !btn.contains(e.target)) {
        volumePanel.classList.remove('visible');
      }
    });
  }

  if (volumeSlider) {
    volumeSlider.min = '0';
    volumeSlider.max = '1';
    volumeSlider.step = '0.01';
    volumeSlider.value = String(audio.volume);
    updateSliderFill();

    volumeSlider.addEventListener('input', function () {
      var v = parseFloat(volumeSlider.value);
      audio.volume = v;
      try { localStorage.setItem('vype-volume', String(v)); } catch (e) {}
      updateSliderFill();
      if (v > 0 && audio.paused) playMusic();
    });

    volumeSlider.addEventListener('click', function (e) { e.stopPropagation(); });
    volumeSlider.addEventListener('mousedown', function (e) { e.stopPropagation(); });
    volumeSlider.addEventListener('touchstart', function (e) { e.stopPropagation(); });
  }

  document.addEventListener('visibilitychange', function () {
    if (document.hidden && !audio.paused) {
      audio.pause();
      setPlayingUI(false);
      if (btn) btn.dataset.wasPlaying = '1';
    } else if (!document.hidden && btn && btn.dataset.wasPlaying === '1') {
      btn.dataset.wasPlaying = '0';
      playMusic();
    }
  });
}

